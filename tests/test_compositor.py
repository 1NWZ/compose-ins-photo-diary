"""Behavioral checks using synthetic fixtures, never personal photos."""
import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
import zipfile

from PIL import Image, ImageDraw, ImageCms

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("diary", ROOT / "scripts/compose_ins_diary.py")
diary = importlib.util.module_from_spec(spec)
spec.loader.exec_module(diary)


class CompositorTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.work = Path(self.temp.name)
        self.photos = []
        for i in range(6):
            im = Image.new("RGB", (400, 300), (40 + i * 30, 130, 170))
            d = ImageDraw.Draw(im)
            d.rectangle((160, 110, 240, 190), fill=(255, 70, 30))
            d.text((20, 20), str(i + 1), fill="white")
            path = self.work / f"photo{i}.png"
            im.save(path)
            self.photos.append(path)
        self.bg = self.work / "background.png"
        # Test fixture only. Production backgrounds must be generated by the host.
        Image.new("RGB", diary.CANVAS, "#efe9df").save(self.bg)
        self.manifest = self.work / "sources.json"
        self.layout_file = self.work / "layout.json"
        self.output = self.work / "result.png"
        self.build()

    def build(self, count=3, mode="bold-index"):
        diary.inspect_sources(self.photos[:count], self.manifest)
        self.layout = {
            "schema_version": 1, "canvas": [1536, 2048], "mode": mode,
            "background": {"path": self.bg.name, "sha256": diary.sha256(self.bg.read_bytes()),
                           "kind": "generated", "prompt": "SYNTHETIC TEST FIXTURE, not a generated example"},
            "photos": [{"source_id": f"photo-{i+1:02d}",
                        "box": [180 + 400*(i % 3), 650 + 500*(i // 3), 280, 210],
                        "focus": [0.5, 0.5], "protected_region": [0.4, 0.35, 0.6, 0.65],
                        "direction_sensitive": True} for i in range(count)],
            "texts": [{"text": "( ordinary things )", "box": [180, 440, 1100, 100],
                       "font_size": 60, "color": "#263A32"}]}
        self.save_layout()

    def save_layout(self):
        diary.write_json(self.layout_file, self.layout)

    def render(self, **kwargs):
        self.save_layout()
        return diary.render(self.manifest, self.layout_file, self.output, **kwargs)

    def test_all_modes_and_source_counts(self):
        for count in range(3, 7):
            for mode in sorted(diary.MODES):
                with self.subTest(count=count, mode=mode):
                    self.build(count, mode)
                    report = self.render()
                    with Image.open(self.output) as im:
                        self.assertEqual(im.size, (1536, 2048))
                        self.assertTrue(im.info.get("icc_profile"))
                        # A source's center marker remains in its actual rendered position.
                        self.assertEqual(im.getpixel((320, 755)), (255, 70, 30))
                    self.assertEqual(len(report["sources"]), count)
                    self.assertEqual({r["id"] for r in report["sources"]},
                                     {f"photo-{i+1:02d}" for i in range(count)})

    def test_sources_unchanged_and_provenance_accurate(self):
        original = [p.read_bytes() for p in self.photos[:3]]
        report = self.render()
        for i, source in enumerate(report["sources"]):
            self.assertEqual(source["sha256"], hashlib.sha256(original[i]).hexdigest())
            self.assertEqual(self.photos[i].read_bytes(), original[i])
            self.assertEqual(source["crop_box_oriented_px"], [0, 0, 400, 300])
        sidecar = json.loads(self.output.with_suffix(".provenance.json").read_text())
        self.assertEqual(sidecar["output"]["sha256"], diary.sha256(self.output.read_bytes()))
        self.assertNotIn(str(self.work), json.dumps(sidecar))

    def test_reproducible_across_processes(self):
        command = [sys.executable, str(ROOT / "scripts/compose_ins_diary.py"), "render",
                   "--manifest", str(self.manifest), "--layout", str(self.layout_file),
                   "--output", str(self.output)]
        subprocess.run(command, check=True, capture_output=True)
        first = self.output.read_bytes()
        subprocess.run(command, check=True, capture_output=True)
        self.assertEqual(first, self.output.read_bytes())

    def test_preview_size(self):
        self.render(preview=True)
        with Image.open(self.output) as im:
            self.assertEqual(im.size, (768, 1024))

    def test_validate_only_writes_no_output(self):
        self.assertTrue(self.render(validate_only=True)["valid"])
        self.assertFalse(self.output.exists())

    def test_count_and_duplicate_input_rejected(self):
        for images in [self.photos[:2], self.photos + [self.photos[0]],
                       [self.photos[0], self.photos[0], self.photos[1]]]:
            with self.subTest(count=len(images)), self.assertRaises(diary.ContractError):
                diary.inspect_sources(images, self.manifest)

    def test_changed_source_rejected(self):
        Image.new("RGB", (400, 300), "black").save(self.photos[0])
        with self.assertRaisesRegex(diary.ContractError, "hash mismatch"):
            self.render()

    def test_missing_duplicate_or_unknown_photo_rejected(self):
        original = copy.deepcopy(self.layout)
        for variant in ("missing", "duplicate", "unknown"):
            self.layout = copy.deepcopy(original)
            if variant == "missing":
                self.layout["photos"].pop()
            elif variant == "duplicate":
                self.layout["photos"][1]["source_id"] = "photo-01"
            else:
                self.layout["photos"][1]["source_id"] = "photo-99"
            with self.subTest(variant=variant), self.assertRaises(diary.ContractError):
                self.render()

    def test_focal_crop_preserves_protected_region(self):
        crop = diary.focal_crop((1200, 600), (300, 300), [0, 0.5], [0.7, 0.2, 0.9, 0.8])
        self.assertLessEqual(crop[0], 840)
        self.assertGreaterEqual(crop[2], 1080)
        self.assertEqual(crop[2] - crop[0], 600)

    def test_impossible_crop_rejected(self):
        self.layout["photos"][0]["box"] = [180, 650, 120, 400]
        self.layout["photos"][0]["protected_region"] = [0, 0, 1, 1]
        with self.assertRaisesRegex(diary.ContractError, "protected subject"):
            self.render()

    def test_rotation_policy_and_out_of_bounds(self):
        self.layout["photos"][0]["rotation"] = 3
        with self.assertRaisesRegex(diary.ContractError, "upright"):
            self.render()
        self.layout["photos"][0]["direction_sensitive"] = False
        self.render()
        self.layout["photos"][0]["box"][0] = 64
        with self.assertRaisesRegex(diary.ContractError, "safe margin"):
            self.render()

    def test_overlaps_and_unknown_fields_rejected(self):
        self.layout["photos"][1]["box"] = self.layout["photos"][0]["box"][:]
        with self.assertRaisesRegex(diary.ContractError, "overlap"):
            self.render()
        self.build()
        self.layout["texts"][0]["box"] = [200, 700, 1100, 100]
        with self.assertRaisesRegex(diary.ContractError, "overlap"):
            self.render()
        self.build()
        self.layout["photos"][0]["shadow"] = True
        with self.assertRaisesRegex(diary.ContractError, "unknown fields"):
            self.render()

    def test_text_overflow_and_unsupported_glyphs_rejected(self):
        self.layout["texts"][0]["box"] = [180, 440, 20, 20]
        with self.assertRaisesRegex(diary.ContractError, "does not fit"):
            self.render()
        self.build()
        self.layout["texts"][0]["text"] = "中文"
        with self.assertRaisesRegex(diary.ContractError, "ASCII"):
            self.render()

    def test_source_cannot_be_background(self):
        self.layout["background"].update(path=self.photos[0].name,
            sha256=diary.sha256(self.photos[0].read_bytes()))
        with self.assertRaisesRegex(diary.ContractError, "cannot serve"):
            self.render()

    def test_output_cannot_overwrite_source(self):
        self.save_layout()
        original = self.photos[0].read_bytes()
        with self.assertRaisesRegex(diary.ContractError, "overwrite"):
            diary.render(self.manifest, self.layout_file, self.photos[0])
        self.assertEqual(original, self.photos[0].read_bytes())

    def test_exif_orientation_and_icc_conversion(self):
        path = self.work / "oriented.jpg"
        im = Image.new("RGB", (80, 40), "red")
        exif = Image.Exif()
        exif[274] = 6
        im.save(path, exif=exif, icc_profile=diary.SRGB.tobytes())
        normalized, info = diary.load_image(path)
        self.assertEqual(normalized.size, (40, 80))
        self.assertEqual(info["exif_orientation"], 6)
        self.assertEqual(info["color_conversion"], "embedded-ICC-to-sRGB")

    def test_animated_and_unsupported_input_rejected(self):
        a = Image.new("RGB", (200, 200), "red")
        b = Image.new("RGB", (200, 200), "blue")
        path = self.work / "animated.png"
        a.save(path, save_all=True, append_images=[b], duration=100, loop=0)
        with self.assertRaisesRegex(diary.ContractError, "Animated"):
            diary.load_image(path)
        path = self.work / "image.bmp"
        a.save(path)
        with self.assertRaisesRegex(diary.ContractError, "Unsupported"):
            diary.load_image(path)

    def test_jpeg_webp_and_transparency(self):
        for extension in ["jpg", "webp"]:
            path = self.work / ("supported." + extension)
            Image.new("RGB", (40, 50), "blue").save(path)
            image, _ = diary.load_image(path)
            self.assertEqual(image.size, (40, 50))
        path = self.work / "alpha.png"
        Image.new("RGBA", (40, 50), (12, 34, 56, 90)).save(path)
        image, _ = diary.load_image(path)
        self.assertEqual(image.getpixel((0, 0)), (12, 34, 56, 90))

    def test_geometry_density_limit(self):
        self.build(6)
        self.layout["texts"][0]["box"][1] = 65
        for i, photo in enumerate(self.layout["photos"]):
            photo["box"] = [64 + 704 * (i % 2), 240 + 580 * (i // 2), 680, 560]
        with self.assertRaisesRegex(diary.ContractError, "35%"):
            self.render()

    def test_duplicate_json_keys_and_nonfinite_numbers(self):
        self.layout_file.write_text('{"mode":"bold-index","mode":"place-note"}')
        with self.assertRaisesRegex(diary.ContractError, "Duplicate JSON key"):
            diary.read_json(self.layout_file)
        self.layout["photos"][0]["focus"][0] = float("nan")
        self.layout_file.write_text(json.dumps(self.layout))
        with self.assertRaisesRegex(diary.ContractError, "finite number"):
            diary.render(self.manifest, self.layout_file, self.output)

    def test_cli_error_has_no_traceback(self):
        result = subprocess.run([sys.executable, str(ROOT / "scripts/compose_ins_diary.py"),
                                 "inspect", "--images", str(self.photos[0]),
                                 "--output", str(self.manifest)], capture_output=True, text=True)
        self.assertEqual(result.returncode, 2)
        self.assertIn("ERROR:", result.stderr)
        self.assertNotIn("Traceback", result.stderr)

    def test_archives_preserve_runtime_and_exclude_development(self):
        destination = self.work / "dist"
        subprocess.run([sys.executable, str(ROOT / "scripts/package_skill.py"),
                        "--output-dir", str(destination)], check=True, capture_output=True)
        skill = destination / "compose-ins-photo-diary.skill"
        with zipfile.ZipFile(skill) as archive:
            names = archive.namelist()
            self.assertIn("compose-ins-photo-diary/SKILL.md", names)
            self.assertEqual(sum(n.endswith("OFL.txt") for n in names), 3)
            self.assertFalse(any("/tests/" in n or "/evals/" in n or "__pycache__" in n for n in names))
            archive.extractall(self.work / "installed")
        installed = self.work / "installed/compose-ins-photo-diary/scripts/compose_ins_diary.py"
        subprocess.run([sys.executable, str(installed), "render", "--manifest", str(self.manifest),
                        "--layout", str(self.layout_file), "--output", str(self.output)],
                       check=True, capture_output=True)
        self.assertTrue(self.output.exists())


if __name__ == "__main__":
    unittest.main()
